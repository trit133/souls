// Builds the three skill trees (travel paths, clusters, keystones, evolutions; no nodes overlap and no lines cross)
// and writes them to src/treelayout.js, which the game loads.
// Run after changing the tree shapes or clusters: node scripts/gen-trees.mjs
import { writeFileSync } from 'fs';
import { generate, saveNode } from '../src/skilltree.js';
const out = {};
for (const kind of ['knight', 'rogue', 'mage']) {
  const t0 = Date.now(), t = generate(kind, (m) => console.log('  ' + m));
  out[kind] = { nodes: [...t.nodes.values()].map(saveNode), edges: t.edges };
  const roles = {}; for (const n of t.nodes.values()) roles[n.role] = (roles[n.role] || 0) + 1;
  console.log(kind, t.nodes.size, 'nodes', JSON.stringify(roles), 'res travel', [...t.nodes.values()].filter((n) => n.res).length, `${Date.now() - t0} ms`);
}
writeFileSync(new URL('../src/treelayout.js', import.meta.url), '// Generated by scripts/gen-trees.mjs: the skill trees (positions, links, stats), worked out once so the game loads fast.\nexport const LAYOUT = ' + JSON.stringify(out) + ';\n');
