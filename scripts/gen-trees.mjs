// Builds the three skill trees (placed so no nodes overlap and no lines cross) and writes their positions to
// src/treelayout.js.
// Run after changing the tree shapes: node scripts/gen-trees.mjs
import { writeFileSync } from 'fs';
import { build } from '../src/skilltree.js';
const out = {};
for (const kind of ['knight', 'rogue', 'mage']) {
  const t = build(kind, { relax: true });
  out[kind] = Object.fromEntries([...t.nodes.values()].map((n) => [n.id, [+n.x.toFixed(2), +n.y.toFixed(2)]]));
  console.log(kind, t.nodes.size, 'nodes laid out');
}
writeFileSync(new URL('../src/treelayout.js', import.meta.url), '// Generated by scripts/gen-trees.mjs: skill tree node positions (worked out once so the game loads fast).\nexport const LAYOUT = ' + JSON.stringify(out) + ';\n');
